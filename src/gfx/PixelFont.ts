export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = ROWS[ch] ?? ROWS['?'];
    for (let r = 0; r < 5; r++)
      for (let c = 0; c < 3; c++) if (g[r][c] === '#') ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
    cx += 4 * scale;
  }
}

export function drawTextVertical(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string) {
  let cy = y;
  for (const ch of text) {
    drawText(ctx, ch, x, cy, scale, color);
    cy += 6 * scale;
  }
}

export const textWidth = (text: string, scale: number) => (text.length * 4 - 1) * scale;
